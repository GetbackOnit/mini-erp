-- =========================================================
-- Mini ERP schema (PostgreSQL / Supabase)
-- 실행 순서: 기존 테이블 삭제 → 기준정보 → 영업 → 생산·재고 → 인덱스
-- =========================================================

BEGIN;

-- 0. 기존 테이블 전부 삭제 (테스트 데이터 포함 모두 사라짐)
DROP TABLE IF EXISTS
  goods_receipts, purchase_order_lines, purchase_orders, suppliers,
  inventory_txns, production_orders, sales_targets,
  shipments, shipment, sales_order_lines, sales_orders,
  bom, warehouses, items, customers, sales_reps
CASCADE;

-- =========================================================
-- 1. 기준정보
-- =========================================================

CREATE TABLE sales_reps (
  rep_id     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name       text NOT NULL,
  team       text,
  hire_date  date
);

CREATE TABLE customers (
  customer_id  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name         text NOT NULL,
  country      text NOT NULL DEFAULT 'KR',
  segment      text NOT NULL CHECK (segment IN ('DOMESTIC', 'OVERSEAS')),  -- 국내/해외
  rep_id       bigint REFERENCES sales_reps(rep_id),
  created_at   date NOT NULL DEFAULT CURRENT_DATE
);

CREATE TABLE items (
  item_id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  item_code      text NOT NULL UNIQUE,                                  -- 예: FG-1001, RM-2001
  name           text NOT NULL,
  item_type      text NOT NULL CHECK (item_type IN ('FG', 'RM')),       -- 완제품/원자재
  unit           text NOT NULL DEFAULT 'EA',
  standard_cost  numeric(12,2) NOT NULL DEFAULT 0 CHECK (standard_cost >= 0),
  list_price     numeric(12,2) CHECK (list_price >= 0)                  -- 원자재는 NULL 가능
);

CREATE TABLE warehouses (
  warehouse_id  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name          text NOT NULL UNIQUE,
  location      text
);

CREATE TABLE bom (
  parent_item_id  bigint NOT NULL REFERENCES items(item_id),
  child_item_id   bigint NOT NULL REFERENCES items(item_id),
  qty_per         numeric(10,3) NOT NULL CHECK (qty_per > 0),
  PRIMARY KEY (parent_item_id, child_item_id),
  CHECK (parent_item_id <> child_item_id)
);

-- =========================================================
-- 2. 영업
-- =========================================================

CREATE TABLE sales_orders (
  order_id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id     bigint NOT NULL REFERENCES customers(customer_id),
  order_date      date NOT NULL,
  requested_date  date,
  status          text NOT NULL DEFAULT 'OPEN'
                  CHECK (status IN ('OPEN', 'PARTIAL', 'SHIPPED', 'CANCELLED')),
  CHECK (requested_date IS NULL OR requested_date >= order_date)
);

CREATE TABLE sales_order_lines (
  order_id    bigint NOT NULL REFERENCES sales_orders(order_id) ON DELETE CASCADE,
  line_no     int NOT NULL CHECK (line_no > 0),
  item_id     bigint NOT NULL REFERENCES items(item_id),
  qty         int NOT NULL CHECK (qty > 0),
  unit_price  numeric(12,2) NOT NULL CHECK (unit_price >= 0),
  PRIMARY KEY (order_id, line_no)
);

CREATE TABLE shipments (
  shipment_id  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id     bigint NOT NULL,
  line_no      int NOT NULL,
  ship_date    date NOT NULL,
  qty          int NOT NULL CHECK (qty > 0),
  FOREIGN KEY (order_id, line_no) REFERENCES sales_order_lines(order_id, line_no)
);

CREATE TABLE sales_targets (
  rep_id         bigint NOT NULL REFERENCES sales_reps(rep_id),
  year_month     date NOT NULL CHECK (EXTRACT(DAY FROM year_month) = 1),  -- 매월 1일로 저장
  target_amount  numeric(14,0) NOT NULL CHECK (target_amount >= 0),
  PRIMARY KEY (rep_id, year_month)
);

-- =========================================================
-- 3. 구매
-- =========================================================

CREATE TABLE suppliers (
  supplier_id     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name            text NOT NULL,
  country         text NOT NULL DEFAULT 'KR',
  lead_time_days  int NOT NULL DEFAULT 7 CHECK (lead_time_days >= 0),   -- 발주 후 입고까지 기본 소요일
  created_at      date NOT NULL DEFAULT CURRENT_DATE
);

CREATE TABLE purchase_orders (
  po_id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  supplier_id    bigint NOT NULL REFERENCES suppliers(supplier_id),
  po_date        date NOT NULL,
  expected_date  date,
  status         text NOT NULL DEFAULT 'OPEN'
                 CHECK (status IN ('OPEN', 'PARTIAL', 'RECEIVED', 'CANCELLED')),
  CHECK (expected_date IS NULL OR expected_date >= po_date)
);

CREATE TABLE purchase_order_lines (
  po_id       bigint NOT NULL REFERENCES purchase_orders(po_id) ON DELETE CASCADE,
  line_no     int NOT NULL CHECK (line_no > 0),
  item_id     bigint NOT NULL REFERENCES items(item_id),
  qty         numeric(12,3) NOT NULL CHECK (qty > 0),
  unit_price  numeric(12,2) NOT NULL CHECK (unit_price >= 0),
  PRIMARY KEY (po_id, line_no)
);

CREATE TABLE goods_receipts (
  gr_id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  po_id         bigint NOT NULL,
  line_no       int NOT NULL,
  receipt_date  date NOT NULL,
  qty           numeric(12,3) NOT NULL CHECK (qty > 0),
  FOREIGN KEY (po_id, line_no) REFERENCES purchase_order_lines(po_id, line_no)
);

-- =========================================================
-- 4. 생산·재고
-- =========================================================

CREATE TABLE production_orders (
  prod_order_id  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  item_id        bigint NOT NULL REFERENCES items(item_id),
  planned_qty    int NOT NULL CHECK (planned_qty > 0),
  completed_qty  int NOT NULL DEFAULT 0 CHECK (completed_qty >= 0),
  start_date     date,
  due_date       date,
  status         text NOT NULL DEFAULT 'PLANNED'
                 CHECK (status IN ('PLANNED', 'IN_PROGRESS', 'DONE', 'CANCELLED'))
);

CREATE TABLE inventory_txns (
  txn_id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  item_id       bigint NOT NULL REFERENCES items(item_id),
  warehouse_id  bigint NOT NULL REFERENCES warehouses(warehouse_id),
  txn_type      text NOT NULL
                CHECK (txn_type IN ('PURCHASE_IN', 'SALES_OUT', 'PROD_ISSUE', 'PROD_RECEIPT', 'ADJUST')),
  qty           numeric(12,3) NOT NULL CHECK (qty <> 0),                -- 입고 +, 출고 -
  txn_date      date NOT NULL,
  ref_type      text CHECK (ref_type IN ('GOODS_RECEIPT', 'SHIPMENT', 'PROD_ORDER', 'ADJUST')),
  ref_id        bigint,                                                 -- 다형 참조라 FK 없음
  CHECK (
       (txn_type IN ('PURCHASE_IN', 'PROD_RECEIPT') AND qty > 0)
    OR (txn_type IN ('SALES_OUT', 'PROD_ISSUE')     AND qty < 0)
    OR  txn_type = 'ADJUST'
  )
);

-- =========================================================
-- 5. FK 컬럼 인덱스 (PostgreSQL은 FK에 인덱스를 자동 생성하지 않음)
-- =========================================================

CREATE INDEX idx_po_supplier          ON purchase_orders(supplier_id);
CREATE INDEX idx_pol_item             ON purchase_order_lines(item_id);
CREATE INDEX idx_gr_line              ON goods_receipts(po_id, line_no);

CREATE INDEX idx_customers_rep        ON customers(rep_id);
CREATE INDEX idx_bom_child            ON bom(child_item_id);
CREATE INDEX idx_so_customer          ON sales_orders(customer_id);
CREATE INDEX idx_sol_item             ON sales_order_lines(item_id);
CREATE INDEX idx_ship_line            ON shipments(order_id, line_no);
CREATE INDEX idx_po_item              ON production_orders(item_id);
CREATE INDEX idx_txn_item_date        ON inventory_txns(item_id, txn_date);
CREATE INDEX idx_txn_warehouse        ON inventory_txns(warehouse_id);

COMMIT;